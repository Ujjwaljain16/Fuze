"""Turn a `pip install --dry-run --report` into a hash-pinned requirements.lock (see lock-requirements.sh)."""
import hashlib
import json
import sys
import urllib.request
from urllib.parse import unquote, urlparse


def file_sha256(name: str, version: str, url: str) -> str:
    filename = unquote(urlparse(url).path.rsplit("/", 1)[-1])
    # Files served by PyTorch's mirror often come without a hash; PyPI publishes one for the same file.
    try:
        meta = json.load(urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30))
        for f in meta.get("urls", []):
            if f["filename"] == filename:
                return f["digests"]["sha256"]
    except Exception:
        pass
    digest = hashlib.sha256()
    with urllib.request.urlopen(url, timeout=300) as resp:
        for chunk in iter(lambda: resp.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main(report_path: str, out_path: str) -> None:
    report = json.load(open(report_path))
    lines = []
    for item in sorted(report["install"], key=lambda i: i["metadata"]["name"].lower()):
        name, version = item["metadata"]["name"], item["metadata"]["version"]
        info = item["download_info"]
        archive = info.get("archive_info", {})
        digest = archive.get("hashes", {}).get("sha256") or archive.get("hash", "").partition("=")[2]
        if not digest:
            digest = file_sha256(name, version, info["url"])
        lines.append(f"{name}=={version} \\\n    --hash=sha256:{digest}")
    header = ("# Generated by scripts/lock-requirements.sh from requirements.txt -- do not edit.\n"
              "# Installed with --require-hashes in the Docker image (python:3.11, linux x86_64).\n"
              "--extra-index-url https://download.pytorch.org/whl/cpu\n\n")
    with open(out_path, "w") as fh:
        fh.write(header + "\n".join(lines) + "\n")
    print(len(lines), "packages locked")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
